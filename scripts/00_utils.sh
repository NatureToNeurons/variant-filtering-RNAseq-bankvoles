set -euo pipefail

###############################################################################
# Logging
###############################################################################

timestamp() {
    date +"%Y-%m-%d %H:%M:%S"
}

log_info() {
    printf "[%s] [INFO] %s\n" "$(timestamp)" "$*"
}

log_warning() {
    printf "[%s] [WARNING] %s\n" "$(timestamp)" "$*" >&2
}

log_error() {
    printf "[%s] [ERROR] %s\n" "$(timestamp)" "$*" >&2
}

###############################################################################
# Exit on Error
###############################################################################

die() {
    log_error "$1"
    exit 1
}

###############################################################################
# Section Headers
###############################################################################

print_header() {

    echo
    echo "======================================================================="
    echo "$1"
    echo "======================================================================="
    echo

}

print_footer() {

    echo
    echo "-----------------------------------------------------------------------"
    echo "$1"
    echo "-----------------------------------------------------------------------"
    echo

}

###############################################################################
# Software Validation
###############################################################################

check_program() {

    local program="$1"

    command -v "$program" >/dev/null 2>&1 \
        || die "$program was not found in PATH."

}

###############################################################################
# File Validation
###############################################################################

check_file() {

    local file="$1"

    [[ -f "$file" ]] \
        || die "Missing file: $file"

}

###############################################################################
# Directory Validation
###############################################################################

check_directory() {

    local directory="$1"

    [[ -d "$directory" ]] \
        || die "Missing directory: $directory"

}

###############################################################################
# Directory Creation
###############################################################################

create_dir() {

    local directory="$1"

    mkdir -p "$directory"

}

###############################################################################
# CPU Detection
###############################################################################

available_threads() {

    if command -v nproc >/dev/null 2>&1
    then
        nproc
    else
        echo 1
    fi

}

###############################################################################
# Disk Space
###############################################################################

check_disk_space() {

    df -h .

}

###############################################################################
# Start Timer
###############################################################################

start_timer() {

    START_TIME=$(date +%s)

}

###############################################################################
# Stop Timer
###############################################################################

stop_timer() {

    END_TIME=$(date +%s)

    ELAPSED=$((END_TIME-START_TIME))

    log_info "Elapsed time: ${ELAPSED} seconds"

}
